        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `CK_SNAPSHOT_CALCULATION_MONTHS`
        CHECK (`CALCULATION_MONTHS` > 0),
    CONSTRAINT `CK_SNAPSHOT_TOTAL_ASSETS`
