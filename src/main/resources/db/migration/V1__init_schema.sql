-- =========================================================
-- 1. 버티 레벨
-- =========================================================
CREATE TABLE IF NOT EXISTS `BUTTIE_LEVEL` (
    `LEVEL` INT NOT NULL,
    `STAGE_NAME` VARCHAR(50) NOT NULL,
    `REQUIRED_EXP` INT NOT NULL,
    `DESCRIPTION` VARCHAR(200) NULL,
    `IMAGE_URL_STABLE` VARCHAR(500) NOT NULL,
    `IMAGE_URL_CAUTION` VARCHAR(500) NOT NULL,
    `IMAGE_URL_DANGER` VARCHAR(500) NOT NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`LEVEL`),
    UNIQUE KEY `UK_BUTTIE_LEVEL_REQUIRED_EXP` (`REQUIRED_EXP`),
    CONSTRAINT `CK_BUTTIE_LEVEL_LEVEL`
        CHECK (`LEVEL` > 0),
    CONSTRAINT `CK_BUTTIE_LEVEL_REQUIRED_EXP`
        CHECK (`REQUIRED_EXP` >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 2. 관리자
-- =========================================================
CREATE TABLE IF NOT EXISTS `ADMIN` (
    `ADMIN_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `EMAIL` VARCHAR(100) NOT NULL,
    `PASSWORD` VARCHAR(255) NOT NULL,
    `ADMIN_ROLE` ENUM('SUPER_ADMIN', 'OPERATOR')
        NOT NULL DEFAULT 'OPERATOR',
    `STATUS` ENUM('ACTIVE', 'LOCKED', 'INACTIVE')
        NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`ADMIN_ID`),
    UNIQUE KEY `UK_ADMIN_EMAIL` (`EMAIL`)
) ENGINE=InnoDB;

-- =========================================================
-- 3. 사용자
-- =========================================================
CREATE TABLE IF NOT EXISTS `USER` (
    `USER_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USERNAME` VARCHAR(30) NOT NULL,
    `EMAIL` VARCHAR(100) NOT NULL,
    `PASSWORD` VARCHAR(255) NOT NULL,
    `NICKNAME` VARCHAR(30) NOT NULL,
    `PHONE_NUMBER` VARCHAR(20) NOT NULL,
    `ONBOARDING_COMPLETED` BOOLEAN NOT NULL DEFAULT FALSE,
    `STATUS` ENUM('ACTIVE', 'LOCKED', 'WITHDRAWN')
        NOT NULL DEFAULT 'ACTIVE',
    `BUTTIE_TOTAL_EXP` INT NOT NULL DEFAULT 0,
    `BUTTIE_LEVEL` INT NOT NULL DEFAULT 1,
    `WITHDRAWN_AT` DATETIME NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`USER_ID`),
    UNIQUE KEY `UK_USER_EMAIL` (`EMAIL`),
    UNIQUE KEY `UK_USER_NICKNAME` (`NICKNAME`),
    UNIQUE KEY `UK_USER_PHONE_NUMBER` (`PHONE_NUMBER`),
    KEY `IDX_USER_STATUS` (`STATUS`),
    KEY `IDX_USER_BUTTIE_LEVEL` (`BUTTIE_LEVEL`),

    CONSTRAINT `FK_USER_BUTTIE_LEVEL`
        FOREIGN KEY (`BUTTIE_LEVEL`)
        REFERENCES `BUTTIE_LEVEL` (`LEVEL`)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT `CK_USER_BUTTIE_TOTAL_EXP`
        CHECK (`BUTTIE_TOTAL_EXP` >= 0),

    CONSTRAINT `CK_USER_WITHDRAWN_AT`
        CHECK (
            (`STATUS` = 'WITHDRAWN' AND `WITHDRAWN_AT` IS NOT NULL)
            OR
            (`STATUS` <> 'WITHDRAWN')
        )
) ENGINE=InnoDB;

-- =========================================================
-- 4. 취업 준비 정보
-- 사용자와 1:1
-- =========================================================
CREATE TABLE IF NOT EXISTS `EMPLOYMENT_PREPARATIONS` (
    `USER_ID` BIGINT NOT NULL,
    `BIRTH_DATE` DATE NOT NULL,
    `REGION` VARCHAR(50) NOT NULL,
    `FAMILY_COUNT` INT NOT NULL DEFAULT 1,
    `EMPLOYMENT_PREP_TYPE`
        ENUM('FIRST_JOB', 'REEMPLOYMENT', 'JOB_CHANGE') NOT NULL,
    `PREP_START_DATE` DATE NOT NULL,
    `TARGET_EMPLOYMENT_DATE` DATE NOT NULL,
    `LIVING_FUND_THRESHOLD` INT NOT NULL DEFAULT 0,
    `EMERGENCY_FUND_THRESHOLD` INT NOT NULL DEFAULT 0,

    PRIMARY KEY (`USER_ID`),
    KEY `IDX_EMPLOYMENT_PREPARATIONS_REGION` (`REGION`),
    KEY `IDX_EMPLOYMENT_PREPARATIONS_TYPE` (`EMPLOYMENT_PREP_TYPE`),

    CONSTRAINT `FK_EMPLOYMENT_PREPARATIONS_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `CK_EMPLOYMENT_PREPARATIONS_FAMILY_COUNT`
        CHECK (`FAMILY_COUNT` >= 1),
    CONSTRAINT `CK_EMPLOYMENT_PREPARATIONS_TARGET_DATE`
        CHECK (`TARGET_EMPLOYMENT_DATE` >= `PREP_START_DATE`),
    CONSTRAINT `CK_EMPLOYMENT_PREPARATIONS_LIVING_FUND`
        CHECK (`LIVING_FUND_THRESHOLD` >= 0),
    CONSTRAINT `CK_EMPLOYMENT_PREPARATIONS_EMERGENCY_FUND`
        CHECK (`EMERGENCY_FUND_THRESHOLD` >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 5. 사용자 약관 동의
