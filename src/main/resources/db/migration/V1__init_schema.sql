    `TARGET_BALANCE` INT NOT NULL DEFAULT 0,
    `ADDITIONAL_REQUIRED_AMOUNT` INT NOT NULL DEFAULT 0,
    `TARGET_ACHIEVEMENT_RATE` DECIMAL(5, 2) NOT NULL DEFAULT 0,
    `RISK_LEVEL` ENUM('STABLE', 'CAUTION', 'DANGER')
