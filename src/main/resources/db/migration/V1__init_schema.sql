    CONSTRAINT `CK_SNAPSHOT_LIQUID_ASSETS`
        CHECK (`LIQUID_ASSETS` >= 0),
    CONSTRAINT `CK_SNAPSHOT_FINANCIAL_PRODUCT_ASSETS`
        CHECK (`FINANCIAL_PRODUCT_ASSETS` >= 0),
    CONSTRAINT `CK_SNAPSHOT_TOTAL_DEBT`
        CHECK (`TOTAL_DEBT` >= 0),
    CONSTRAINT `CK_SNAPSHOT_AVG_MONTHLY_INCOME`
        CHECK (`AVG_MONTHLY_INCOME` >= 0),
    CONSTRAINT `CK_SNAPSHOT_AVG_MONTHLY_EXPENSE`
        CHECK (`AVG_MONTHLY_EXPENSE` >= 0),
    CONSTRAINT `CK_SNAPSHOT_PREP_POSSIBLE_MONTHS`
        CHECK (`PREP_POSSIBLE_MONTHS` IS NULL OR `PREP_POSSIBLE_MONTHS` >= 0),
    CONSTRAINT `CK_SNAPSHOT_ADDITIONAL_REQUIRED_AMOUNT`
        CHECK (`ADDITIONAL_REQUIRED_AMOUNT` >= 0),
    CONSTRAINT `CK_SNAPSHOT_TARGET_ACHIEVEMENT_RATE`
        CHECK (`TARGET_ACHIEVEMENT_RATE` >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 11. 금융 상품
-- =========================================================
CREATE TABLE IF NOT EXISTS `FINANCE` (
    `FINANCE_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `COMPANY` VARCHAR(20) NOT NULL,
    `NAME` VARCHAR(200) NOT NULL,
    `TYPE` ENUM('DEPOSIT', 'SAVINGS') NOT NULL,
    `MIN_AGE` INT NULL,
    `MAX_AGE` INT NULL,
    `PERIOD` INT NOT NULL,
    `BASE_RATE` DECIMAL(5, 2) NOT NULL DEFAULT 0,
    `PREFERRED_RATE` DECIMAL(5, 2) NULL,
    `MINIMUM_AMOUNT` INT NULL,
    `REGISTER_CONDITION` TEXT NULL,
    `WITHDRAW_CONDITION` TEXT NULL,
    `URL` VARCHAR(500) NULL,
    `STATUS` ENUM('AVAILABLE', 'CLOSED')
        NOT NULL DEFAULT 'AVAILABLE',

    PRIMARY KEY (`FINANCE_ID`),
    KEY `IDX_FINANCE_TYPE_STATUS` (`TYPE`, `STATUS`),
    KEY `IDX_FINANCE_AGE` (`MIN_AGE`, `MAX_AGE`),

    CONSTRAINT `CK_FINANCE_AGE_RANGE`
        CHECK (
            (`MIN_AGE` IS NULL OR `MIN_AGE` >= 0)
            AND
            (`MAX_AGE` IS NULL OR `MAX_AGE` >= 0)
            AND
            (`MIN_AGE` IS NULL OR `MAX_AGE` IS NULL OR `MAX_AGE` >= `MIN_AGE`)
        ),
    CONSTRAINT `CK_FINANCE_PERIOD`
        CHECK (`PERIOD` > 0),
    CONSTRAINT `CK_FINANCE_BASE_RATE`
        CHECK (`BASE_RATE` >= 0),
    CONSTRAINT `CK_FINANCE_PREFERRED_RATE`
        CHECK (`PREFERRED_RATE` IS NULL OR `PREFERRED_RATE` >= 0),
    CONSTRAINT `CK_FINANCE_MINIMUM_AMOUNT`
        CHECK (`MINIMUM_AMOUNT` IS NULL OR `MINIMUM_AMOUNT` >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 12. 정부 지원 정책
