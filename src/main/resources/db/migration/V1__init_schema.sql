            AND
            (`MAX_AGE` IS NULL OR `MAX_AGE` >= 0)
            AND
            (`MIN_AGE` IS NULL OR `MAX_AGE` IS NULL OR `MAX_AGE` >= `MIN_AGE`)
        ),
    CONSTRAINT `CK_POLICY_AMOUNT`
        CHECK (`AMOUNT` IS NULL OR `AMOUNT` >= 0),
    CONSTRAINT `CK_POLICY_FAMILY_COUNT`
        CHECK (`FAMILY_COUNT` >= 1)
) ENGINE=InnoDB;

-- =========================================================
-- 13. 시뮬레이션
-- =========================================================
CREATE TABLE IF NOT EXISTS `SIMULATION` (
    `SIMULATION_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `SNAPSHOT_ID` BIGINT NOT NULL,
    `START_DATE` DATETIME NOT NULL,
    `END_DATE` DATETIME NOT NULL,
    `ENDING_BALANCE` INT NOT NULL,
    `TARGET_RATE` DECIMAL(5, 2) NOT NULL,
    `PREP_MONTHS` DECIMAL(5, 2) NULL,
    `CREATED_AT` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `MODIFIED_AT` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    `CONFIRMED_AT` TIMESTAMP NULL,
    `IS_DELETED` BOOLEAN NOT NULL DEFAULT FALSE,

    PRIMARY KEY (`SIMULATION_ID`),
    KEY `IDX_SIMULATION_USER_CREATED_AT` (`USER_ID`, `CREATED_AT`),
    KEY `IDX_SIMULATION_SNAPSHOT_ID` (`SNAPSHOT_ID`),
    KEY `IDX_SIMULATION_IS_DELETED` (`IS_DELETED`),

    CONSTRAINT `FK_SIMULATION_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_SIMULATION_SNAPSHOT`
        FOREIGN KEY (`SNAPSHOT_ID`)
        REFERENCES `SNAPSHOT` (`SNAPSHOT_ID`)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT `CK_SIMULATION_DATE_RANGE`
        CHECK (`END_DATE` >= `START_DATE`),
    CONSTRAINT `CK_SIMULATION_TARGET_RATE`
        CHECK (`TARGET_RATE` >= 0),
    CONSTRAINT `CK_SIMULATION_PREP_MONTHS`
        CHECK (`PREP_MONTHS` IS NULL OR `PREP_MONTHS` >= 0)
) ENGINE=InnoDB;

-- =========================================================
-- 14. 시뮬레이션 적용 항목
-- =========================================================
CREATE TABLE IF NOT EXISTS `SIMULATION_ITEM` (
    `SIMULATION_ITEM_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `SIMULATION_ID` BIGINT NOT NULL,
    `CATEGORY` ENUM('POLICY', 'FINANCIAL', 'EXPENSE', 'INCOME') NOT NULL,
    `AMOUNT` INT NOT NULL DEFAULT 0,
    `START_DATE` DATETIME NOT NULL,
    `END_DATE` DATETIME NULL,
    `POLICY_ID` BIGINT NULL,
    `FINANCE_ID` BIGINT NULL,
    `DETAIL_VALUE` TEXT NULL,
    `RECURRENCE_TYPE` ENUM('ONCE', 'WEEKLY', 'MONTHLY')
        NOT NULL DEFAULT 'ONCE',
    `IS_DELETED` BOOLEAN NOT NULL DEFAULT FALSE,

    PRIMARY KEY (`SIMULATION_ITEM_ID`),
    KEY `IDX_SIMULATION_ITEM_SIMULATION_ID` (`SIMULATION_ID`),
    KEY `IDX_SIMULATION_ITEM_CATEGORY` (`CATEGORY`),
    KEY `IDX_SIMULATION_ITEM_POLICY_ID` (`POLICY_ID`),
    KEY `IDX_SIMULATION_ITEM_FINANCE_ID` (`FINANCE_ID`),
    KEY `IDX_SIMULATION_ITEM_IS_DELETED` (`IS_DELETED`),

    CONSTRAINT `FK_SIMULATION_ITEM_SIMULATION`
        FOREIGN KEY (`SIMULATION_ID`)
        REFERENCES `SIMULATION` (`SIMULATION_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_SIMULATION_ITEM_POLICY`
        FOREIGN KEY (`POLICY_ID`)
        REFERENCES `POLICY` (`POLICY_ID`)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT `FK_SIMULATION_ITEM_FINANCE`
        FOREIGN KEY (`FINANCE_ID`)
        REFERENCES `FINANCE` (`FINANCE_ID`)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    CONSTRAINT `CK_SIMULATION_ITEM_DATE_RANGE`
        CHECK (`END_DATE` IS NULL OR `END_DATE` >= `START_DATE`),

    CONSTRAINT `CK_SIMULATION_ITEM_REFERENCE`
        CHECK (
            (`CATEGORY` = 'POLICY' AND `POLICY_ID` IS NOT NULL AND `FINANCE_ID` IS NULL)
            OR
            (`CATEGORY` = 'FINANCIAL' AND `FINANCE_ID` IS NOT NULL AND `POLICY_ID` IS NULL)
            OR
            (`CATEGORY` IN ('EXPENSE', 'INCOME')
                AND `POLICY_ID` IS NULL
                AND `FINANCE_ID` IS NULL)
        )
) ENGINE=InnoDB;

