-- =========================================================
-- 7. 계좌
-- =========================================================
CREATE TABLE IF NOT EXISTS `ACCOUNT` (
    `ACCOUNT_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `MYDATA_ID` BIGINT NULL,
    `EXTERNAL_ACCOUNT_ID` VARCHAR(100) NOT NULL,
    `INSTITUTION_NAME` VARCHAR(100) NOT NULL,
    `ACCOUNT_NAME` VARCHAR(100) NOT NULL,
    `ACCOUNT_TYPE`
        ENUM('CHECKING', 'SAVINGS', 'DEPOSIT', 'LOAN', 'CARD') NOT NULL,
    `ACCOUNT_NUMBER_MASKED` VARCHAR(50) NULL,
    `BALANCE` INT NOT NULL DEFAULT 0,
    `IS_ACTIVE` BOOLEAN NOT NULL DEFAULT TRUE,
    `SYNCED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`ACCOUNT_ID`),
    UNIQUE KEY `UK_ACCOUNT_MYDATA_EXTERNAL`
        (`MYDATA_ID`, `EXTERNAL_ACCOUNT_ID`),
    KEY `IDX_ACCOUNT_USER_ID` (`USER_ID`),
    KEY `IDX_ACCOUNT_TYPE` (`ACCOUNT_TYPE`),
    KEY `IDX_ACCOUNT_IS_ACTIVE` (`IS_ACTIVE`),

    CONSTRAINT `FK_ACCOUNT_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_ACCOUNT_MYDATA`
        FOREIGN KEY (`MYDATA_ID`)
        REFERENCES `MYDATA` (`MYDATA_ID`)
        ON UPDATE CASCADE
        ON DELETE SET NULL
) ENGINE=InnoDB;

-- =========================================================
-- 8. 거래
-- =========================================================
CREATE TABLE IF NOT EXISTS `TRANSACTION` (
    `TRANSACTION_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `ACCOUNT_ID` BIGINT NULL,
    `EXTERNAL_TRANSACTION_ID` VARCHAR(100) NULL,
    `CONTENT` VARCHAR(255) NOT NULL,
    `IS_EXPENSE` BOOLEAN NOT NULL DEFAULT FALSE,
    `CATEGORY`
        ENUM(
            'FOOD',
            'TRANSPORT',
            'HOUSING',
            'COMMUNICATION',
            'SUBSCRIPTION',
            'EDUCATION',
            'CERTIFICATE',
            'ETC_EXPENSE'
        ) NOT NULL DEFAULT 'ETC_EXPENSE',
    `AMOUNT` INT NOT NULL,
    `TRANSACTION_AT` DATETIME NOT NULL,
    `MEMO` VARCHAR(500) NULL,
    `ANALYSIS_EXCLUDED` BOOLEAN NOT NULL DEFAULT FALSE,
    `IS_DELETED` BOOLEAN NOT NULL DEFAULT FALSE,
    `DELETED_AT` DATETIME NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`TRANSACTION_ID`),
    UNIQUE KEY `UK_TRANSACTION_ACCOUNT_EXTERNAL`
        (`ACCOUNT_ID`, `EXTERNAL_TRANSACTION_ID`),
    KEY `IDX_TRANSACTION_USER_AT` (`USER_ID`, `TRANSACTION_AT`),
    KEY `IDX_TRANSACTION_ACCOUNT_ID` (`ACCOUNT_ID`),
    KEY `IDX_TRANSACTION_CATEGORY` (`CATEGORY`),
    KEY `IDX_TRANSACTION_IS_EXPENSE` (`IS_EXPENSE`),
    KEY `IDX_TRANSACTION_ANALYSIS_EXCLUDED` (`ANALYSIS_EXCLUDED`),
    KEY `IDX_TRANSACTION_IS_DELETED` (`IS_DELETED`),

    CONSTRAINT `FK_TRANSACTION_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_TRANSACTION_ACCOUNT`
        FOREIGN KEY (`ACCOUNT_ID`)
        REFERENCES `ACCOUNT` (`ACCOUNT_ID`)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT `CK_TRANSACTION_AMOUNT`
        CHECK (`AMOUNT` > 0),

    CONSTRAINT `CK_TRANSACTION_DELETED_AT`
        CHECK (
            (`IS_DELETED` = TRUE AND `DELETED_AT` IS NOT NULL)
            OR
            (`IS_DELETED` = FALSE)
        )
) ENGINE=InnoDB;

-- =========================================================
-- 9. 사용자 설정 비용
-- 고정 지출 및 예정 비용
-- =========================================================
CREATE TABLE IF NOT EXISTS `CUSTOM_EXPENSE` (
    `CUSTOM_EXPENSE_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `IS_FIXED` BOOLEAN NOT NULL DEFAULT TRUE,
    `NAME` VARCHAR(100) NOT NULL,
    `CATEGORY` VARCHAR(50) NOT NULL,
    `AMOUNT` INT NOT NULL,
    `EXPECTED_DATE` DATE NOT NULL,
    `IS_RECURRING` BOOLEAN NOT NULL DEFAULT FALSE,
    `RECURRENCE_TYPE` ENUM('WEEKLY', 'MONTHLY') NULL,
    `RECURRENCE_END_DATE` DATE NULL,
    `STATUS` ENUM('ACTIVE', 'COMPLETED', 'CANCELLED')
        NOT NULL DEFAULT 'ACTIVE',
    `MEMO` VARCHAR(500) NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (`CUSTOM_EXPENSE_ID`),
    KEY `IDX_CUSTOM_EXPENSE_USER_DATE` (`USER_ID`, `EXPECTED_DATE`),
    KEY `IDX_CUSTOM_EXPENSE_STATUS` (`STATUS`),
    KEY `IDX_CUSTOM_EXPENSE_IS_FIXED` (`IS_FIXED`),

    CONSTRAINT `FK_CUSTOM_EXPENSE_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `CK_CUSTOM_EXPENSE_AMOUNT`
        CHECK (`AMOUNT` > 0),

    CONSTRAINT `CK_CUSTOM_EXPENSE_RECURRENCE`
        CHECK (
            (`IS_RECURRING` = FALSE
                AND `RECURRENCE_TYPE` IS NULL
                AND `RECURRENCE_END_DATE` IS NULL)
            OR
            (`IS_RECURRING` = TRUE
                AND `RECURRENCE_TYPE` IS NOT NULL)
        ),

    CONSTRAINT `CK_CUSTOM_EXPENSE_RECURRENCE_END_DATE`
        CHECK (
            `RECURRENCE_END_DATE` IS NULL
            OR `RECURRENCE_END_DATE` >= `EXPECTED_DATE`
        )
) ENGINE=InnoDB;

-- =========================================================
-- 10. 재정 스냅샷
