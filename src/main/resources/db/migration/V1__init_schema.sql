    `CATEGORY` VARCHAR(50) NOT NULL,
    `MIN_AGE` INT NULL,
    `MAX_AGE` INT NULL,
    `REGION` VARCHAR(50) NULL,
    `AMOUNT` INT NULL,
    `DUE_DATE` DATETIME NOT NULL,
    `DOCUMENT` TEXT NULL,
    `EMPLOYMENT_STATUS` VARCHAR(50) NULL,
    `FAMILY_COUNT` INT NOT NULL DEFAULT 1,
    `STATUS` ENUM('AVAILABLE', 'CLOSED')
        NOT NULL DEFAULT 'AVAILABLE',
    `URL` VARCHAR(500) NULL,

    PRIMARY KEY (`POLICY_ID`),
    KEY `IDX_POLICY_CATEGORY_STATUS` (`CATEGORY`, `STATUS`),
    KEY `IDX_POLICY_REGION` (`REGION`),
    KEY `IDX_POLICY_DUE_DATE` (`DUE_DATE`),
    KEY `IDX_POLICY_AGE` (`MIN_AGE`, `MAX_AGE`),

    CONSTRAINT `CK_POLICY_AGE_RANGE`
        CHECK (
