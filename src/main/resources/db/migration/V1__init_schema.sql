-- =========================================================
-- 17. 퀘스트
-- =========================================================
CREATE TABLE IF NOT EXISTS `QUEST` (
    `QUEST_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `SIMULATION_ID` BIGINT NOT NULL,
    `SIMULATION_ITEM_ID` BIGINT NOT NULL,
    `TRANSACTION_ID` BIGINT NULL,
    `QUEST_TYPE` ENUM('APPLY', 'SUBMIT', 'CANCEL', 'CHECK', 'ETC') NOT NULL,
    `TITLE` VARCHAR(100) NOT NULL,
    `DESCRIPTION` TEXT NULL,
    `DEADLINE` DATETIME NULL,
    `STATUS` ENUM('PLANNED', 'IN_PROGRESS', 'COMPLETED')
        NOT NULL DEFAULT 'PLANNED',
    `URL` VARCHAR(500) NULL,
    `EXP_REWARD` INT NULL DEFAULT 0,
    `COMPLETED_AT` DATETIME NULL,

    PRIMARY KEY (`QUEST_ID`),
    KEY `IDX_QUEST_USER_STATUS_DEADLINE`
        (`USER_ID`, `STATUS`, `DEADLINE`),
    KEY `IDX_QUEST_SIMULATION_ID` (`SIMULATION_ID`),
    KEY `IDX_QUEST_SIMULATION_ITEM_ID` (`SIMULATION_ITEM_ID`),
    KEY `IDX_QUEST_TRANSACTION_ID` (`TRANSACTION_ID`),

    CONSTRAINT `FK_QUEST_USER`
        FOREIGN KEY (`USER_ID`)
        REFERENCES `USER` (`USER_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_QUEST_SIMULATION`
        FOREIGN KEY (`SIMULATION_ID`)
        REFERENCES `SIMULATION` (`SIMULATION_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_QUEST_SIMULATION_ITEM`
        FOREIGN KEY (`SIMULATION_ITEM_ID`)
        REFERENCES `SIMULATION_ITEM` (`SIMULATION_ITEM_ID`)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT `FK_QUEST_TRANSACTION`
        FOREIGN KEY (`TRANSACTION_ID`)
        REFERENCES `TRANSACTION` (`TRANSACTION_ID`)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT `CK_QUEST_EXP_REWARD`
        CHECK (`EXP_REWARD` IS NULL OR `EXP_REWARD` >= 0),

    CONSTRAINT `CK_QUEST_COMPLETED_AT`
        CHECK (
            (`STATUS` = 'COMPLETED' AND `COMPLETED_AT` IS NOT NULL)
            OR
            (`STATUS` <> 'COMPLETED')
        )
) ENGINE=InnoDB;
