    `USER_ID` BIGINT NOT NULL,
    `BASE_DATE` DATE NOT NULL,
    `CALCULATION_MONTHS` INT NOT NULL DEFAULT 3,
    `TOTAL_ASSETS` INT NOT NULL DEFAULT 0,
    `LIQUID_ASSETS` INT NOT NULL DEFAULT 0,
    `FINANCIAL_PRODUCT_ASSETS` INT NOT NULL DEFAULT 0,
    `TOTAL_DEBT` INT NOT NULL DEFAULT 0,
